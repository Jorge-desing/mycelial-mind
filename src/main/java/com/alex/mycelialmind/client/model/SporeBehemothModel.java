    @Override
    public void setupAnim(T entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
        boolean isMutatedOrHigher = false;
        boolean isEliteRank = false;
        if (entity instanceof com.alex.mycelialmind.entity.MycelialMob mycelialMob) {
            var rank = mycelialMob.getEvolutionRank();
            isMutatedOrHigher = rank != com.alex.mycelialmind.hive.EvolutionRank.BASE;
            isEliteRank = rank == com.alex.mycelialmind.hive.EvolutionRank.ELITE;
        } else if (entity instanceof com.alex.mycelialmind.entity.MycelialChimeraEntity chimeraRank) {
            var rank = chimeraRank.getEvolutionRank();
            isMutatedOrHigher = rank != com.alex.mycelialmind.hive.EvolutionRank.BASE;
            isEliteRank = rank == com.alex.mycelialmind.hive.EvolutionRank.ELITE;
        }
        float attackSwing = Mth.sin(this.attackTime * (float) Math.PI);
        float[] sp = this.springState.computeIfAbsent(entity, e -> new float[]{0.0F, 0.0F, e.getYRot(), 0.0F, 0.0F, ageInTicks});
        float dt = Mth.clamp((ageInTicks - sp[5]) * 0.05F, 0.0F, 0.10F);
        sp[5] = ageInTicks;
        float dYaw = Mth.wrapDegrees(entity.getYRot() - sp[2]);
        if (dt > 0.0F) sp[2] = entity.getYRot();
        float dVert = (float) entity.getDeltaMovement().y;
        float yawGoal = Mth.clamp(dYaw * 0.016F, -0.42F, 0.42F);
        float pitchGoal = Mth.clamp(dVert * 0.38F, -0.42F, 0.42F);
        stepSpringDamperExact(sp, 0, yawGoal, 0.18F, dt);
        stepSpringDamperExact(sp, 3, pitchGoal, 0.22F, dt);
        float jiggle = damperExact(sp[0] + sp[3] * 0.6F, sp[0] + sp[3] * 0.6F, 0.08F, dt);
        float br_torso = 1.0F + Mth.sin(ageInTicks * 0.09F + 0.0F) * 0.025F * 1.0F;
        this.torso.xScale = br_torso;
        this.torso.zScale = br_torso;
        this.torso.xRot = 0.14F + Mth.sin(ageInTicks * 0.09F + 0.0F) * 0.03F;
        this.head.yRot = netHeadYaw * ((float) Math.PI / 180F);
        this.head.xRot = 0.0F + headPitch * ((float) Math.PI / 180F);
        this.jawNode.xRot = 0.0F + 0.08F + Mth.sin(ageInTicks * 0.16F + 0.0F) * 0.12F + attackSwing * 0.42F;
        float pulse_hunchSac = 1.0F + Mth.sin(ageInTicks * 0.14F + 0.0F) * 0.08F * 1.0F + jiggle * 0.10F;
        this.hunchSac.xScale = pulse_hunchSac;
        this.hunchSac.yScale = pulse_hunchSac;
        this.hunchSac.zScale = pulse_hunchSac;
        this.hunchSac.zRot = 0.0F + jiggle * 0.18F;
        float piston_pressurePistons = Mth.sin(ageInTicks * 0.22F + 0.0F) * 0.06F * 1.0F;
        this.pressurePistons.xScale = 1.0F + piston_pressurePistons + attackSwing * 0.22F;
        this.pressurePistons.yScale = 1.0F - piston_pressurePistons * 0.82F + attackSwing * 0.10F;
        this.mutatedMortarPods.visible = isMutatedOrHigher;
        float pulse_mutatedMortarPods = 1.0F + Mth.sin(ageInTicks * 0.14F + 0.0F) * 0.08F * 1.0F + jiggle * 0.10F;
        this.mutatedMortarPods.xScale = pulse_mutatedMortarPods;
        this.mutatedMortarPods.yScale = pulse_mutatedMortarPods;
        this.mutatedMortarPods.zScale = pulse_mutatedMortarPods;
        this.mutatedMortarPods.zRot = 0.0F + jiggle * 0.18F;
        this.mutatedBehemothSpikes.visible = isMutatedOrHigher;
        this.eliteBehemothCrown.visible = isEliteRank;
        this.armR.xRot = 0.0F + Mth.cos(limbSwing * 0.6662F + (float) Math.PI) * 1.05F * limbSwingAmount - 0.18F + Mth.sin(ageInTicks * 0.09F + 0.0F) * 0.08F - attackSwing * 1.45F;
        this.maceForearm.xRot = 0.0F - 0.35F + Mth.sin(ageInTicks * 0.10F + 0.0F) * 0.12F + attackSwing * 0.55F;
        float piston_ramPistons = Mth.sin(ageInTicks * 0.22F + 0.6F) * 0.06F * 1.0F;
        this.ramPistons.xScale = 1.0F + piston_ramPistons + attackSwing * 0.22F;
        this.ramPistons.yScale = 1.0F - piston_ramPistons * 0.82F + attackSwing * 0.10F;
        this.armL.xRot = 0.0F + Mth.cos(limbSwing * 0.6662F) * 0.85F * limbSwingAmount * 1.0F - attackSwing * 0.65F;
        this.clawForearm.xRot = 0.0F - 0.35F + Mth.sin(ageInTicks * 0.10F + 1.2F) * 0.12F + attackSwing * 0.55F;
        this.eliteSiegeCrown.visible = isEliteRank;
        this.eliteSiegeCrown.yRot = -ageInTicks * 0.07F * -1.0F;
        this.eliteSiegeCrown.zRot = 0.45F + Mth.cos(ageInTicks * 0.05F + 0.0F) * 0.15F;
        this.rightLeg.xRot = 0.0F + Mth.cos(limbSwing * 0.6662F) * 1.1F * limbSwingAmount * 1.0F;
        this.leftLeg.xRot = 0.0F + Mth.cos(limbSwing * 0.6662F + (float) Math.PI) * 1.1F * limbSwingAmount * 1.0F;
        if (entity instanceof com.alex.mycelialmind.entity.MycelialBossMob boss) {
            float bossProg = boss.getStateProgress();
            switch (boss.getCombatState()) {
                case WINDUP -> {
                    this.torso.xRot -= 0.22F * bossProg;
                    this.armR.xRot -= 1.05F * bossProg;
                    this.armL.xRot -= 0.85F * bossProg;
                }
                case ACTIVE -> {
                    this.torso.xRot += 0.28F;
                    this.armR.xRot += 0.85F;
                    this.armL.xRot += 0.65F;
                }
                case STAGGERED -> {
                    this.torso.xRot += 0.42F;
                    this.head.xRot += 0.35F;
                    this.armR.xRot += 0.32F;
                    this.armL.xRot += 0.32F;
                }
                default -> {
                    if (boss.isCarapaceBroken()) {
                        this.torso.xRot += 0.24F;
                    }
                }
            }
        }
    }

    private static float damperExact(float x, float goal, float halflife, float dt) {
        float y = (4.0F * 0.6931472F) / Math.max(1.0E-4F, halflife);
        float ydt = y * dt;
        float e = 1.0F / (1.0F + ydt + 0.48F * ydt * ydt + 0.235F * ydt * ydt * ydt);
        return goal + (x - goal) * e;
    }

    private static void stepSpringDamperExact(float[] state, int offset, float targetGoal, float halflife, float dt) {
        float y = (4.0F * 0.6931472F) / Math.max(1.0E-4F, halflife);
        float ydt = y * dt;
        float e = 1.0F / (1.0F + ydt + 0.48F * ydt * ydt + 0.235F * ydt * ydt * ydt);
        float j0 = state[offset] - targetGoal;
        float j1 = state[offset + 1] + j0 * y;
        state[offset] = Mth.clamp(e * (j0 + j1 * dt) + targetGoal, -0.45F, 0.45F);
        state[offset + 1] = e * (state[offset + 1] - j1 * y * dt);
    }

