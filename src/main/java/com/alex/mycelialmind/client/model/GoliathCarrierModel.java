    public void renderToBuffer(PoseStack poseStack, VertexConsumer buffer, int packedLight, int packedOverlay, int color) {
        this.body.render(poseStack, buffer, packedLight, packedOverlay, color);
        this.legFl.render(poseStack, buffer, packedLight, packedOverlay, color);
        this.legFr.render(poseStack, buffer, packedLight, packedOverlay, color);
        this.legBl.render(poseStack, buffer, packedLight, packedOverlay, color);
        this.legBr.render(poseStack, buffer, packedLight, packedOverlay, color);
    }
