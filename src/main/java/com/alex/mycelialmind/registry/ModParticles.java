package com.alex.mycelialmind.registry;

import com.alex.mycelialmind.MycelialMind;
import com.mojang.serialization.MapCodec;
import net.minecraft.core.particles.ColorParticleOption;
import net.minecraft.core.particles.ParticleType;
import net.minecraft.core.particles.SimpleParticleType;
import net.minecraft.core.registries.Registries;
import net.minecraft.network.RegistryFriendlyByteBuf;
import net.minecraft.network.codec.StreamCodec;
import net.neoforged.bus.api.IEventBus;
import net.neoforged.neoforge.registries.DeferredHolder;
import net.neoforged.neoforge.registries.DeferredRegister;

import java.util.List;

/**
 * Every particle silhouette used by the mod.
 *
 * <p>Each entry is backed by a {@code particles/<id>.json} sprite list and a
 * matching set of {@code textures/particle/<id>[_n].png} frames generated by
 * {@code scripts/particle_studio/}. {@link #HIVE_DUST} is a tintable
 * {@link ColorParticleOption} type so strain/rank colours never multiply the
 * registry.</p>
 */
public final class ModParticles {
    private static final DeferredRegister<ParticleType<?>> PARTICLES =
            DeferredRegister.create(Registries.PARTICLE_TYPE, MycelialMind.MODID);

    // --- Status effects -------------------------------------------------
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> INFECTION = register("infection");
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> ROT = register("rot");
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> INSIGHT = register("insight");
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> VISION = register("vision");

    // --- Consumables, serums & scanner ----------------------------------
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> RECOVERY = register("recovery");
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> PURGE = register("purge");
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> SCAN = register("scan");
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> SERUM_MELEE = register("serum_melee");
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> SERUM_PROJECTILE = register("serum_projectile");
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> SERUM_FIRE = register("serum_fire");
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> SERUM_EXPLOSION = register("serum_explosion");
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> SERUM_MAGIC = register("serum_magic");
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> ENGRAM = register("engram");
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> IMPACT = register("impact");
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> TRAIL = register("trail");

    // --- Organic hive, world & combat -----------------------------------
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> SPORE_MOTE = register("spore_mote");
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> SPORE_CLOUD = register("spore_cloud");
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> SPORE_FALL = register("spore_fall");
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> BIO_LUME = register("bio_lume");
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> AMBER_GLINT = register("amber_glint");
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> CHITIN_SHARD = register("chitin_shard");
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> ACID_DROPLET = register("acid_droplet");
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> ACID_SPLASH = register("acid_splash");
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> NECROTIC_MIST = register("necrotic_mist");

    // --- Neural, hive network, bosses & purification ---------------------
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> SYNAPSE_SPARK = register("synapse_spark");
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> HIVE_PULSE = register("hive_pulse");
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> PSYCHIC_WAVE = register("psychic_wave");
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> TIDE_MOTE = register("tide_mote");
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> HIVE_EMBER = register("hive_ember");
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> PURIFIER_CROSS = register("purifier_cross");
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> THERMAL_RETICLE = register("thermal_reticle");
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> HISTAMINE_PULSE = register("histamine_pulse");
    public static final DeferredHolder<ParticleType<?>, SimpleParticleType> DESYNC_FRAGMENT = register("desync_fragment");

    /** Tintable dust used for strain hues, rank auras and chitin debris. */
    public static final DeferredHolder<ParticleType<?>, ParticleType<ColorParticleOption>> HIVE_DUST =
            registerColorable("hive_dust");

    private static final List<DeferredHolder<ParticleType<?>, ?>> ALL = List.<DeferredHolder<ParticleType<?>, ?>>of(
            INFECTION, ROT, INSIGHT, VISION,
            RECOVERY, PURGE, SCAN,
            SERUM_MELEE, SERUM_PROJECTILE, SERUM_FIRE, SERUM_EXPLOSION, SERUM_MAGIC, ENGRAM, IMPACT, TRAIL,
            SPORE_MOTE, SPORE_CLOUD, SPORE_FALL, BIO_LUME, AMBER_GLINT, CHITIN_SHARD,
            ACID_DROPLET, ACID_SPLASH, NECROTIC_MIST,
            SYNAPSE_SPARK, HIVE_PULSE, PSYCHIC_WAVE, TIDE_MOTE, HIVE_EMBER,
            PURIFIER_CROSS, THERMAL_RETICLE, HISTAMINE_PULSE, DESYNC_FRAGMENT, HIVE_DUST
    );

    private static DeferredHolder<ParticleType<?>, SimpleParticleType> register(String id) {
        return PARTICLES.register(id, () -> new SimpleParticleType(false));
    }

    private static DeferredHolder<ParticleType<?>, ParticleType<ColorParticleOption>> registerColorable(String id) {
        return PARTICLES.register(id, () -> new ParticleType<>(false) {
            @Override
            public MapCodec<ColorParticleOption> codec() {
                return ColorParticleOption.codec(this);
            }

            @Override
            public StreamCodec<? super RegistryFriendlyByteBuf, ColorParticleOption> streamCodec() {
                return ColorParticleOption.streamCodec(this);
            }
        });
    }

    /** Immutable view of every registered particle type, used by tests and audits. */
    public static List<DeferredHolder<ParticleType<?>, ?>> all() {
        return ALL;
    }

    public static void register(IEventBus bus) {
        PARTICLES.register(bus);
    }

    private ModParticles() {}
}
